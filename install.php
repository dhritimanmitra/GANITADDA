    <div class="col-md-6"><input class="form-control" name="db_user" placeholder="Database username" value="<?= h($v['db_user']) ?>" required></div>
    <div class="col-md-6"><input class="form-control" type="password" name="db_pass" placeholder="Database password"></div></div>
    <h2 class="h6 mt-4">First administrator</h2>
    <div class="row g-2"><div class="col-12"><input class="form-control" name="admin_name" placeholder="Your name" value="<?= h($v['admin_name']) ?>" required></div>
