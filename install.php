  <li>Private PDFs will be stored in: <code><?= h($storagePath) ?></code></li></ol>
<?php else: ?>
  <ul class="list-unstyled small"><?php foreach ($checks as $label => $ok): ?><li><?= $ok ? '✅' : '❌' ?> <?= h($label) ?></li><?php endforeach; ?></ul>
