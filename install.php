<?php
declare(strict_types=1);
// GANIT ADDA installer. Run once, then it deletes itself (or delete it manually).
define('ROOT_PATH', __DIR__);
$https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');
session_name('GANITINSTALL');
session_set_cookie_params(['lifetime' => 0, 'path' => '/', 'secure' => $https, 'httponly' => true, 'samesite' => 'Lax']);
session_start();
function h($v): string { return htmlspecialchars((string)$v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }

if (is_file(__DIR__ . '/includes/config.php')) {
    http_response_code(403);
    exit('<h2>Ganit Adda is already installed.</h2><p>Please delete <code>install.php</code> from your server.</p>');
}
if (empty($_SESSION['csrf'])) { $_SESSION['csrf'] = bin2hex(random_bytes(32)); }

$checks = [
    'PHP 8.2 or higher (you have ' . PHP_VERSION . ')' => version_compare(PHP_VERSION, '8.2.0', '>='),
    'PDO MySQL extension' => extension_loaded('pdo_mysql'),
    'Fileinfo extension (secure uploads)' => extension_loaded('fileinfo'),
    'mbstring extension' => extension_loaded('mbstring'),
    'includes/ folder is writable' => is_writable(__DIR__ . '/includes'),
];
$ready = !in_array(false, $checks, true);
$errors = []; $done = false; $v = ['db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'admin_name' => '', 'admin_email' => ''];

if (($_SERVER['REQUEST_METHOD'] ?? '') === 'POST' && $ready) {
    if (!hash_equals($_SESSION['csrf'], (string)($_POST['csrf'] ?? ''))) { exit('Session expired. Refresh the page.'); }
    foreach (['db_host', 'db_name', 'db_user', 'admin_name', 'admin_email'] as $k) { $v[$k] = trim((string)($_POST[$k] ?? '')); }
    $dbPass = (string)($_POST['db_pass'] ?? ''); $apass = (string)($_POST['admin_pass'] ?? ''); $apass2 = (string)($_POST['admin_pass2'] ?? '');

    if ($v['db_host'] === '' || $v['db_name'] === '' || $v['db_user'] === '') { $errors[] = 'Please fill in all database fields.'; }
    if ($v['admin_name'] === '') { $errors[] = 'Enter the administrator name.'; }
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) { $errors[] = 'Enter a valid administrator email.'; }
    if (strlen($apass) < 10 || !preg_match('/[A-Za-z]/', $apass) || !preg_match('/\d/', $apass)) { $errors[] = 'Password must be at least 10 characters with letters and numbers.'; }
    if ($apass !== $apass2) { $errors[] = 'The two passwords do not match.'; }

    if (!$errors) {
        try {
            $pdo = new PDO('mysql:host=' . $v['db_host'] . ';dbname=' . $v['db_name'] . ';charset=utf8mb4', $v['db_user'], $dbPass,
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        } catch (Throwable $e) {
            $errors[] = 'Could not connect to the database. Check host, name, username and password. (' . $e->getMessage() . ')';
        }
    }
    if (!$errors) {
        try {
            $sql = (string)file_get_contents(__DIR__ . '/database.sql');
            $sql = preg_replace('/^\s*--.*$/m', '', $sql);
            foreach (preg_split('/;\s*[\r\n]+/', $sql) as $stmt) { if (trim($stmt) !== '') { $pdo->exec($stmt); } }
            if ((int)$pdo->query('SELECT COUNT(*) FROM admins')->fetchColumn() > 0) { throw new RuntimeException('An administrator already exists in this database.'); }
            $pdo->prepare('INSERT INTO admins (name, email, password_hash) VALUES (?,?,?)')
                ->execute([$v['admin_name'], strtolower($v['admin_email']), password_hash($apass, PASSWORD_DEFAULT)]);

            $private = dirname(__DIR__) . '/ganit_private';
            if (!(is_dir($private) || @mkdir($private, 0750, true)) || !is_writable($private)) { $private = __DIR__ . '/storage'; }
            foreach (['worksheets', 'solutions', 'uploads'] as $d) { if (!is_dir("$private/$d")) { @mkdir("$private/$d", 0750, true); } }
            if (!is_dir(__DIR__ . '/assets/uploads')) { @mkdir(__DIR__ . '/assets/uploads', 0755, true); }

            $base = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'])), '/');
            $cfg = "<?php\n// Generated by install.php. Keep this file private.\n"
                . 'define(' . var_export('DB_HOST', true) . ', ' . var_export($v['db_host'], true) . ");\n"
                . 'define(' . var_export('DB_NAME', true) . ', ' . var_export($v['db_name'], true) . ");\n"
                . 'define(' . var_export('DB_USER', true) . ', ' . var_export($v['db_user'], true) . ");\n"
                . 'define(' . var_export('DB_PASS', true) . ', ' . var_export($dbPass, true) . ");\n"
                . 'define(\'BASE_URL\', ' . var_export($base, true) . ");\n"
                . 'define(\'STORAGE_PATH\', ' . var_export($private, true) . ");\n"
                . 'define(\'APP_KEY\', ' . var_export(bin2hex(random_bytes(32)), true) . ");\n"
                . "define('MAX_UPLOAD_MB', 15);\ndefine('DEBUG_MODE', false);\n";
            if (file_put_contents(__DIR__ . '/includes/config.php', $cfg, LOCK_EX) === false) { throw new RuntimeException('Could not write includes/config.php.'); }
            @chmod(__DIR__ . '/includes/config.php', 0640);
            $done = true; $removed = @unlink(__FILE__); $storagePath = $private;
        } catch (Throwable $e) {
            $errors[] = 'Installation failed: ' . $e->getMessage();
        }
    }
}
